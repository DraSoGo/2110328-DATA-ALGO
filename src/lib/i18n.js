// UI language (en / th). t(key, vars) looks up the current language, falls back
// to English, and fills {placeholders}. Module step messages stay in English.

const STORAGE_KEY = 'data-algo-lang';
let lang = 'en';

export const LANGS = ['en', 'th'];

export function getLang() {
  return lang;
}

function apply() {
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function initLang() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (LANGS.includes(saved)) lang = saved;
  } catch { /* storage unavailable */ }
  apply();
  return lang;
}

export function setLang(next) {
  lang = LANGS.includes(next) ? next : 'en';
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* storage unavailable */ }
  apply();
}

export function t(key, vars = {}) {
  const text = DICT[lang]?.[key] ?? DICT.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}

// Plural helper for English; Thai has no plural form.
export function plural(count) {
  return lang === 'en' && count !== 1 ? 's' : '';
}

